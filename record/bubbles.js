(() => {
  const ids = new Set();
  for (const [mood, list] of Object.entries(BUBBLE_MESSAGES)){
    if (list.length !== 50) throw new Error(`${mood}: 문구 개수가 50개가 아닙니다.`);
    if (new Set(list.map(x => x[1])).size !== 50) throw new Error(`${mood}: 중복 문구가 있습니다.`);
    for (const [id] of list){ if (ids.has(id)) throw new Error(`${id}: id 가 겹칩니다.`); ids.add(id); }
  }
})();
